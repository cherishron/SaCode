import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,writeFileSync,readFileSync,existsSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
import {createRequire} from 'node:module';
const {HostBridge}=createRequire(import.meta.url)('../../../desktop/host-bridge.cjs');
test('真实Host和CLI恢复同一诊断决定，读取与保留不启动OpenCode或模型任务',{timeout:30000},async t=>{
 assert.ok(process.env.SACODE_HOST);assert.ok(process.env.SACODE_CLI);
 const root=mkdtempSync(join(tmpdir(),'sacode-acp-journal-')),methods=join(root,'methods');
 writeFileSync(join(root,'acp'),"const fs=require('node:fs');require('node:readline').createInterface({input:process.stdin}).on('line',s=>{const q=JSON.parse(s);fs.appendFileSync('methods',q.method+'\\n');let result;if(q.method==='initialize')result={protocolVersion:1,agentCapabilities:{},agentInfo:{name:'fixture',version:'2.fixture'}};else if(q.method==='session/new')result={sessionId:'fixture',configOptions:[{category:'mode',type:'select',currentValue:'plan'}],modes:{currentModeId:'legacy-build'}};else throw Error('model-task-forbidden');console.log(JSON.stringify({jsonrpc:'2.0',id:q.id,result}));});");
 const env={...process.env,SACODE_ACP_OPENCODE_EXECUTABLE:process.execPath,SACODE_USER_SETTINGS_DIR:join(root,'settings')};
 const first=new HostBridge(process.env.SACODE_HOST,env);t.after(()=>first.stop(10000));await first.start(root);
 assert.equal((await first.request('acp/diagnostics/describe',{sessionId:'current'})).record,null);assert.equal(existsSync(methods),false);
 await first.request('workspace/set-directory',{sessionId:'current',directory:root});
 await first.request('acp/settings/set-enabled',{sessionId:'current',enabled:true,revision:0});
 const report=await first.request('acp/provider/probe',{sessionId:'current'},30000);assert.equal(report.protocolReady,true);assert.equal(report.diagnostics.sessionMode,'plan');
 const history=await first.request('acp/diagnostics/describe',{sessionId:'current'});assert.equal(history.scopeCurrent,true);
 const args={sessionId:'current',diagnosticId:history.record.diagnosticId,revision:history.record.revision};
 await assert.rejects(first.request('acp/diagnostics/keep',{...args,diagnosticId:'other'}),/conflict/);
 assert.equal((await first.stop(10000)).forced,false);
 const cli=spawnSync(process.env.SACODE_CLI,['acp','keep',args.diagnosticId,String(args.revision)],{cwd:root,env,encoding:'utf8',windowsHide:true,timeout:10000});
 assert.equal(cli.status,0,cli.stderr);assert.equal(JSON.parse(cli.stdout).record.decision,'kept');
 const second=new HostBridge(process.env.SACODE_HOST,env);t.after(()=>second.stop(10000));await second.start(root);
 const restored=await second.request('acp/diagnostics/describe',{sessionId:'current'});assert.equal(restored.record.decision,'kept');assert.equal(restored.source,'durable-history');
 assert.equal((await second.request('acp/diagnostics/keep',args)).record.revision,2);
 assert.equal(readFileSync(methods,'utf8'),'initialize\nsession/new\n');
 const before=readFileSync(join(root,'session.log'),'utf8');assert.equal((before.match(/\tacp\/diagnostic\t/g)||[]).length,2);
 assert.equal((await second.stop(10000)).forced,false);
 const read=spawnSync(process.env.SACODE_CLI,['acp','diagnostics'],{cwd:root,env,encoding:'utf8',windowsHide:true,timeout:10000});
 assert.equal(read.status,0,read.stderr);assert.equal(JSON.parse(read.stdout).record.decision,'kept');
 assert.equal(readFileSync(join(root,'session.log'),'utf8'),before);assert.equal(readFileSync(methods,'utf8'),'initialize\nsession/new\n');
});

test('启动位置不存在时双入口返回具体诊断，保留开启选择且可以保留现状',{timeout:20000},async t=>{
 const root=mkdtempSync(join(tmpdir(),'sacode-acp-no-instance-'));
 const env={...process.env,SACODE_ACP_OPENCODE_EXECUTABLE:join(root,'no-installed-instance.exe'),SACODE_USER_SETTINGS_DIR:join(root,'settings')};
 const bridge=new HostBridge(process.env.SACODE_HOST,env);t.after(()=>bridge.stop(10000));await bridge.start(root);
 await bridge.request('workspace/set-directory',{sessionId:'current',directory:root});
 await bridge.request('acp/settings/set-enabled',{sessionId:'current',enabled:true,revision:0});
 const report=await bridge.request('acp/provider/probe',{sessionId:'current'},30000);
 assert.equal(report.protocolReady,false);assert.equal(report.modelTaskTested,false);assert.equal(report.diagnosticSaved,true);
 assert.match(report.evidence,/opencode-(executable-not-found|discovery-unconfirmed)/);assert.doesNotMatch(report.evidence,/auth-required/);
 const history=await bridge.request('acp/diagnostics/describe',{sessionId:'current'});
 await bridge.request('acp/diagnostics/keep',{sessionId:'current',diagnosticId:history.record.diagnosticId,revision:history.record.revision});
 assert.equal((await bridge.request('acp/settings/describe',{sessionId:'current'})).enabled,true);
 assert.equal((await bridge.stop(10000)).forced,false);
 const cli=spawnSync(process.env.SACODE_CLI,['acp','probe'],{cwd:root,env,encoding:'utf8',windowsHide:true,timeout:10000});
 assert.equal(cli.status,2,cli.stderr);assert.equal(JSON.parse(cli.stdout).diagnosticSaved,true);
 assert.equal(readFileSync(join(root,'session.log'),'utf8').includes('acp/task/start'),false);
});
