import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,mkdirSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
import {createRequire} from 'node:module';
import {fixtureHostEnv} from '../../../desktop/test-support/fixture-env.mjs';
const {HostBridge}=createRequire(import.meta.url)('../../../desktop/host-bridge.cjs');
test('CodeBuddy独立开关默认关闭，不继承OpenCode开启或执行任意启动向量',{timeout:30000},async t=>{
 const root=mkdtempSync(join(tmpdir(),'sacode-cb-off-'));
 const bridge=new HostBridge(process.env.SACODE_HOST,fixtureHostEnv(root,{SACODE_ACP_CODEBUDDY_EXECUTABLE:join(root,'never-spawn.exe')}));
 await bridge.start(root);t.after(()=>bridge.stop(10000));await bridge.request('workspace/set-directory',{sessionId:'current',directory:root});
 await bridge.request('acp/settings/set-enabled',{sessionId:'current',enabled:true,revision:0});
 assert.equal((await bridge.request('acp/settings/describe',{sessionId:'current',peerId:'codebuddy'})).enabled,false);
 await assert.rejects(bridge.request('acp/provider/probe',{sessionId:'current',peerId:'codebuddy'}),/acp-disabled/);
 await assert.rejects(bridge.request('acp/provider/probe',{sessionId:'current',peerId:'codebuddy',executable:'cmd'}),/invalid-input/);
 await assert.rejects(bridge.request('acp/provider/probe',{sessionId:'current',peerId:'arbitrary-command'}),/provider-not-registered/);
 assert.equal((await bridge.request('acp/diagnostics/describe',{sessionId:'current',peerId:'codebuddy'})).record,null);
 assert.equal((await bridge.stop(10000)).forced,false);
});
test('真实CodeBuddy隔离配置经Host和CLI持久诊断，默认模型由提供方决定且零任务',{timeout:60000,skip:!process.env.SACODE_ACP_CODEBUDDY_TEST_EXECUTABLE},async t=>{
 const root=mkdtempSync(join(tmpdir(),'sacode-cb-control-')),profile=join(root,'provider-profile');mkdirSync(profile);
 const env=fixtureHostEnv(root,{SACODE_ACP_CODEBUDDY_EXECUTABLE:process.env.SACODE_ACP_CODEBUDDY_TEST_EXECUTABLE,CODEBUDDY_CONFIG_DIR:profile,DISABLE_AUTOUPDATER:'1'});
 const bridge=new HostBridge(process.env.SACODE_HOST,env);await bridge.start(root);t.after(()=>bridge.stop(10000));
 await bridge.request('workspace/set-directory',{sessionId:'current',directory:root});
 await bridge.request('acp/settings/set-enabled',{sessionId:'current',peerId:'codebuddy',enabled:true,revision:0});
 const report=await bridge.request('acp/provider/probe',{sessionId:'current',peerId:'codebuddy'},30000);
 assert.equal(report.peerId,'codebuddy');assert.equal(report.protocolReady,true,report.evidence);assert.equal(report.modelTaskTested,false);assert.equal(report.diagnosticSaved,true);
 assert.ok(report.diagnostics.sessionModel);assert.equal((await bridge.request('acp/settings/describe',{sessionId:'current'})).enabled,false);
 const history=await bridge.request('acp/diagnostics/describe',{sessionId:'current',peerId:'codebuddy'});
 await bridge.request('acp/diagnostics/keep',{sessionId:'current',peerId:'codebuddy',diagnosticId:history.record.diagnosticId,revision:history.record.revision});
 assert.equal((await bridge.request('acp/diagnostics/describe',{sessionId:'current'})).record,null);
 await bridge.request('acp/settings/set-enabled',{sessionId:'current',enabled:false,revision:0});
 const kept=await bridge.request('acp/diagnostics/describe',{sessionId:'current',peerId:'codebuddy'});assert.equal(kept.scopeCurrent,true);
 assert.equal((await bridge.stop(10000)).forced,false);
 const before=readFileSync(join(root,'session.log'),'utf8');
 const run=(...args)=>spawnSync(process.env.SACODE_CLI,['acp',...args],{cwd:root,env,encoding:'utf8',windowsHide:true,timeout:10000});
 const restored=run('codebuddy','diagnostics');assert.equal(restored.status,0,restored.stderr);assert.deepEqual(JSON.parse(restored.stdout),kept);
 const settings=run('codebuddy','settings');assert.equal(settings.status,0);assert.equal(JSON.parse(settings.stdout).enabled,true);
 assert.equal(readFileSync(join(root,'session.log'),'utf8'),before);assert.equal(before.includes('acp/task/start'),false);
});
