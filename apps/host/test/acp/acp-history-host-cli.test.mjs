import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,writeFileSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {spawnSync} from 'node:child_process';
import {createRequire} from 'node:module';
const {HostBridge}=createRequire(import.meta.url)('../../../desktop/host-bridge.cjs');
test('ACP真实Host与CLI读取同一持久终态且不重放任务',{timeout:30000},async t=>{
  assert.ok(process.env.SACODE_HOST,'需要本批Host');assert.ok(process.env.SACODE_CLI,'需要本批CLI');
  const dir=mkdtempSync(join(tmpdir(),'sacode-acp-history-'));
  const admission={schema:1,id:'delegation-1',sessionId:'current',taskId:'task-1',requestId:'request-1',peerId:'fixture-peer',workspace:dir,taskDigest:'a'.repeat(64),revision:1,phase:'initializing'};
  const fact={schema:1,delegationId:'delegation-1',sessionId:'current',taskId:'task-1',requestId:'request-1',protocolSessionId:'external-1',protocolRequestId:3,revision:3,phase:'running',detail:'intent-before-send'};
  const ended={...fact,revision:4,phase:'completed',detail:'prompt-stop:end_turn'};
  const path=join(dir,'session.log');
  const logField=text=>text.replaceAll('\\','\\\\').replaceAll('\t','\\t').replaceAll('\n','\\n').replaceAll('\r','\\r');
  writeFileSync(path,[[0,'acp/admission',admission],[1,'acp/task/start',fact],[2,'acp/task/settled',ended]].map(([seq,type,data])=>seq+'\t'+type+'\t'+logField(JSON.stringify(data))+'\n').join(''));
  const bridge=new HostBridge(process.env.SACODE_HOST,{...process.env,SACODE_USER_SETTINGS_DIR:join(dir,'settings')});
  t.after(()=>bridge.stop());await bridge.start(dir);
  const before=readFileSync(path);
  const list=await bridge.request('acp/delegation/list',{sessionId:'current'});
  assert.equal(list.delegations.length,1);assert.equal(list.delegations[0].phase,'completed');assert.equal(list.delegations[0].source,'durable-history');
  const detail=await bridge.request('acp/delegation/describe',{sessionId:'current',delegationId:'delegation-1'});
  assert.deepEqual(detail.delegation,list.delegations[0]);
  await assert.rejects(bridge.request('acp/delegation/list',{sessionId:'other'}),/acp-session-changed/);
  await assert.rejects(bridge.request('acp/delegation/list',{sessionId:'current',start:true}),/invalid-input/);
  const cli=(...args)=>spawnSync(process.env.SACODE_CLI,args,{cwd:dir,env:process.env,encoding:'utf8',windowsHide:true,timeout:10000});
  const cliList=cli('acp','list');assert.equal(cliList.status,0,cliList.stderr);assert.deepEqual(JSON.parse(cliList.stdout),list);
  const cliDetail=cli('acp','describe','delegation-1');assert.equal(cliDetail.status,0,cliDetail.stderr);assert.deepEqual(JSON.parse(cliDetail.stdout),detail);
  const absent=cli('acp','describe','missing');assert.equal(absent.status,1);assert.match(absent.stderr,/not-found/);
  assert.equal(cli('acp','start').status,64);
  assert.deepEqual(readFileSync(path),before,'只读历史不得改写会话日志');
});
